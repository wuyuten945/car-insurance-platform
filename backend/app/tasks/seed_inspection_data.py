async def seed_inspection_data():
    """重建全台監理站及驗車廠資料"""
    await create_tables()

    async with AsyncSessionLocal() as db:
        # 清除舊資料
        await db.execute(delete(InspectionStation))

        count = 0
        for row in ALL_STATIONS:
            (name, stype, city, district, address, phone, lat, lon,
             hours, motorcycle, heavy, services) = row
            db.add(InspectionStation(
                station_name=name,
                station_type=stype,
                city=city,
                district=district,
                address=address,
                phone=phone,
                latitude=lat,
                longitude=lon,
                operating_hours=hours,
                supports_motorcycle=motorcycle,
                supports_heavy=heavy,
                booking_url="https://www.mvdis.gov.tw",
                services=services,
            ))
            count += 1

        await db.commit()
        supervision = sum(1 for r in ALL_STATIONS if r[1] == "supervision")
        inspection = sum(1 for r in ALL_STATIONS if r[1] == "inspection")
        print(f"Inspection data seeded: {count} stations ({supervision} supervision + {inspection} inspection)")


if __name__ == "__main__":
    asyncio.run(seed_inspection_data())
